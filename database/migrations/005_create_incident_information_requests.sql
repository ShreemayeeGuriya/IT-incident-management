-- Persist technician requests for reporter information and the reporter's single response.
BEGIN;

CREATE TABLE incident_information_requests (
    information_request_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id                  INTEGER NOT NULL,
    requesting_technician_user_id INTEGER NOT NULL,
    reporter_user_id              INTEGER NOT NULL,
    request_message               VARCHAR(3000) NOT NULL,
    requested_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    response_status               VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    response_message              VARCHAR(3000),
    responded_at                  TIMESTAMPTZ,
    CONSTRAINT fk_information_requests_incident
        FOREIGN KEY (incident_id) REFERENCES incidents(incident_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_information_requests_technician
        FOREIGN KEY (requesting_technician_user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_information_requests_reporter
        FOREIGN KEY (reporter_user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_information_requests_status
        CHECK (response_status IN ('OPEN', 'RESPONDED')),
    CONSTRAINT chk_information_requests_response
        CHECK ((response_status = 'OPEN' AND response_message IS NULL AND responded_at IS NULL)
            OR (response_status = 'RESPONDED' AND response_message IS NOT NULL AND responded_at IS NOT NULL)),
    CONSTRAINT chk_information_requests_messages
        CHECK (length(btrim(request_message)) > 0
            AND (response_message IS NULL OR length(btrim(response_message)) > 0))
);

CREATE INDEX idx_information_requests_incident_requested
    ON incident_information_requests(incident_id, requested_at ASC, information_request_id ASC);

COMMIT;
