BEGIN;
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('EMPLOYEE', 'TECHNICIAN', 'ADMIN'))
);


CREATE TABLE technicians (
    technician_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL UNIQUE,
    max_workload        INTEGER NOT NULL DEFAULT 5,
    availability_status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    experience_level    VARCHAR(30),
    CONSTRAINT fk_technicians_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_technicians_max_workload
        CHECK (max_workload >= 0),
    CONSTRAINT chk_technicians_availability
        CHECK (availability_status IN ('AVAILABLE', 'BUSY', 'UNAVAILABLE'))
);


CREATE TABLE skills (
    skill_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE technician_skills (
    technician_id    INTEGER NOT NULL,
    skill_id         INTEGER NOT NULL,
    proficiency_level VARCHAR(30),
    CONSTRAINT pk_technician_skills
        PRIMARY KEY (technician_id, skill_id),
    CONSTRAINT fk_technician_skills_technician
        FOREIGN KEY (technician_id) REFERENCES technicians(technician_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_technician_skills_skill
        FOREIGN KEY (skill_id) REFERENCES skills(skill_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);


CREATE TABLE categories (
    category_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name  VARCHAR(100) NOT NULL UNIQUE,
    description    TEXT
);

CREATE TABLE services (
    service_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name  VARCHAR(150) NOT NULL UNIQUE,
    description   TEXT
);


CREATE TABLE sla_policies (
    sla_policy_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name              VARCHAR(100) NOT NULL,
    priority                 VARCHAR(20) NOT NULL,
    response_time_minutes    INTEGER NOT NULL,
    resolution_time_minutes  INTEGER NOT NULL,
    CONSTRAINT chk_sla_policies_priority
        CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT chk_sla_response_time
        CHECK (response_time_minutes > 0),
    CONSTRAINT chk_sla_resolution_time
        CHECK (resolution_time_minutes > 0),
    CONSTRAINT uq_sla_policies_priority UNIQUE (priority)
);


CREATE TABLE incidents (
    incident_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id              INTEGER NOT NULL,
    assigned_technician_id   INTEGER,
    category_id              INTEGER NOT NULL,
    service_id               INTEGER NOT NULL,
    sla_policy_id            INTEGER,
    description              TEXT NOT NULL,
    impact                   VARCHAR(20) NOT NULL,
    urgency                  VARCHAR(20) NOT NULL,
    business_criticality     VARCHAR(20) NOT NULL,
    priority                 VARCHAR(20) NOT NULL,
    status                   VARCHAR(30) NOT NULL DEFAULT 'REPORTED',
    sla_status               VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED',
    response_sla_status      VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED',
    resolution_sla_status    VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED',
    investigation_details    TEXT,
    resolution_details       TEXT,
    closure_details          TEXT,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    first_response_at        TIMESTAMPTZ,
    resolved_at              TIMESTAMPTZ,
    closed_at                TIMESTAMPTZ,
    response_deadline        TIMESTAMPTZ,
    resolution_deadline      TIMESTAMPTZ,

    CONSTRAINT fk_incidents_reporter
        FOREIGN KEY (reporter_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_incidents_assigned_technician
        FOREIGN KEY (assigned_technician_id) REFERENCES technicians(technician_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_incidents_category
        FOREIGN KEY (category_id) REFERENCES categories(category_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_incidents_service
        FOREIGN KEY (service_id) REFERENCES services(service_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_incidents_sla_policy
        FOREIGN KEY (sla_policy_id) REFERENCES sla_policies(sla_policy_id)
        ON UPDATE CASCADE ON DELETE SET NULL,

    CONSTRAINT chk_incidents_impact
        CHECK (impact IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT chk_incidents_urgency
        CHECK (urgency IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT chk_incidents_business_criticality
        CHECK (business_criticality IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT chk_incidents_priority
        CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT chk_incidents_status
        CHECK (status IN (
            'REPORTED', 'CLASSIFIED', 'PRIORITIZED', 'ASSIGNED',
            'INVESTIGATING', 'RESOLVED', 'VERIFIED', 'CLOSED'
        )),
    CONSTRAINT chk_incidents_sla_status
        CHECK (sla_status IN (
            'NOT_STARTED', 'WITHIN_SLA', 'RESPONSE_BREACHED',
            'RESOLUTION_BREACHED', 'BREACHED', 'MET'
        )),
    CONSTRAINT chk_incidents_response_sla_status
        CHECK (response_sla_status IN ('NOT_STARTED', 'WITHIN_SLA', 'APPROACHING_BREACH', 'BREACHED', 'MET')),
    CONSTRAINT chk_incidents_resolution_sla_status
        CHECK (resolution_sla_status IN ('NOT_STARTED', 'WITHIN_SLA', 'APPROACHING_BREACH', 'BREACHED', 'MET')),
    CONSTRAINT chk_incidents_timestamps
        CHECK (
            (first_response_at IS NULL OR first_response_at >= created_at)
            AND (resolved_at IS NULL OR resolved_at >= created_at)
            AND (closed_at IS NULL OR closed_at >= created_at)
        )
);


CREATE TABLE incident_escalations (
    escalation_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id       INTEGER NOT NULL,
    escalation_level  INTEGER NOT NULL,
    trigger_objective VARCHAR(20) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_incident_escalations_incident
        FOREIGN KEY (incident_id) REFERENCES incidents(incident_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_incident_escalations_incident_level
        UNIQUE (incident_id, escalation_level),
    CONSTRAINT chk_incident_escalations_level_objective
        CHECK ((escalation_level = 1 AND trigger_objective = 'RESPONSE')
            OR (escalation_level = 2 AND trigger_objective = 'RESOLUTION'))
);


CREATE TABLE audit_logs (
    audit_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    INTEGER NOT NULL,
    actor_user_id  INTEGER,
    action         VARCHAR(100) NOT NULL,
    old_value      TEXT,
    new_value      TEXT,
    description    TEXT,
    "timestamp"    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_logs_incident
        FOREIGN KEY (incident_id) REFERENCES incidents(incident_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_audit_logs_actor
        FOREIGN KEY (actor_user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE comments (
    comment_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id INTEGER NOT NULL,
    author_id   INTEGER NOT NULL,
    text        VARCHAR(3000) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comments_incident FOREIGN KEY (incident_id)
        REFERENCES incidents(incident_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id)
        REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT
);


CREATE TABLE notifications (
    notification_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL,
    incident_id       INTEGER,
    message           TEXT NOT NULL,
    notification_type VARCHAR(50) NOT NULL,
    delivery_status   VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    is_read           BOOLEAN NOT NULL DEFAULT FALSE,
    event_key         VARCHAR(160),
    delivery_attempts INTEGER NOT NULL DEFAULT 0,
    last_delivery_error TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at           TIMESTAMPTZ,
    CONSTRAINT fk_notifications_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_incident
        FOREIGN KEY (incident_id) REFERENCES incidents(incident_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_notifications_delivery_status
        CHECK (delivery_status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT chk_notifications_read_timestamp
        CHECK (read_at IS NULL OR is_read = TRUE),
    CONSTRAINT chk_notifications_delivery_attempts CHECK (delivery_attempts >= 0)
);

CREATE TABLE incident_information_requests (
    information_request_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id                  INTEGER NOT NULL,
    requesting_technician_user_id INTEGER NOT NULL,
    reporter_user_id              INTEGER NOT NULL,
    request_message               VARCHAR(3000) NOT NULL,
    requested_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    response_status               VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    response_message              VARCHAR(3000),
    responded_at                  TIMESTAMPTZ,
    CONSTRAINT fk_information_requests_incident
        FOREIGN KEY (incident_id) REFERENCES incidents(incident_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_information_requests_technician
        FOREIGN KEY (requesting_technician_user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_information_requests_reporter
        FOREIGN KEY (reporter_user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_information_requests_status
        CHECK (response_status IN ('OPEN', 'RESPONDED')),
    CONSTRAINT chk_information_requests_response
        CHECK ((response_status = 'OPEN' AND response_message IS NULL AND responded_at IS NULL)
            OR (response_status = 'RESPONDED' AND response_message IS NOT NULL AND responded_at IS NOT NULL)),
    CONSTRAINT chk_information_requests_messages
        CHECK (length(btrim(request_message)) > 0
            AND (response_message IS NULL OR length(btrim(response_message)) > 0))
);


CREATE INDEX idx_technicians_availability
    ON technicians(availability_status);

CREATE INDEX idx_technician_skills_skill
    ON technician_skills(skill_id);

CREATE INDEX idx_incidents_reporter
    ON incidents(reporter_id);

CREATE INDEX idx_incidents_assigned_technician
    ON incidents(assigned_technician_id);

CREATE INDEX idx_incidents_category
    ON incidents(category_id);

CREATE INDEX idx_incidents_service
    ON incidents(service_id);

CREATE INDEX idx_incidents_sla_policy
    ON incidents(sla_policy_id);

CREATE INDEX idx_incidents_created_at
    ON incidents(created_at DESC);

CREATE INDEX idx_incidents_status_priority
    ON incidents(status, priority);

CREATE INDEX idx_incidents_sla_status
    ON incidents(sla_status);

CREATE INDEX idx_incidents_response_deadline
    ON incidents(response_deadline)
    WHERE response_deadline IS NOT NULL;

CREATE INDEX idx_incidents_resolution_deadline
    ON incidents(resolution_deadline)
    WHERE resolution_deadline IS NOT NULL;

CREATE INDEX idx_incident_escalations_incident_created
    ON incident_escalations(incident_id, created_at DESC);

CREATE INDEX idx_comments_incident_created_at ON comments(incident_id, created_at ASC);

CREATE UNIQUE INDEX uq_notifications_event_key ON notifications(event_key) WHERE event_key IS NOT NULL;

CREATE INDEX idx_audit_logs_incident_timestamp
    ON audit_logs(incident_id, "timestamp" DESC);

CREATE INDEX idx_audit_logs_actor_timestamp
    ON audit_logs(actor_user_id, "timestamp" DESC);

CREATE INDEX idx_notifications_user_created
    ON notifications(user_id, created_at DESC);

CREATE INDEX idx_notifications_unread
    ON notifications(user_id, created_at DESC)
    WHERE is_read = FALSE;

CREATE INDEX idx_notifications_incident
    ON notifications(incident_id)
    WHERE incident_id IS NOT NULL;

CREATE TABLE incident_information_requests (
    information_request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id INTEGER NOT NULL,
    requesting_technician_user_id INTEGER NOT NULL,
    reporter_user_id INTEGER NOT NULL,
    request_message VARCHAR(3000) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    response_status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    response_message VARCHAR(3000),
    responded_at TIMESTAMPTZ,
    CONSTRAINT fk_information_requests_incident FOREIGN KEY (incident_id)
        REFERENCES incidents(incident_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_information_requests_technician FOREIGN KEY (requesting_technician_user_id)
        REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_information_requests_reporter FOREIGN KEY (reporter_user_id)
        REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_information_request_status CHECK (response_status IN ('OPEN', 'RESPONDED')),
    CONSTRAINT chk_information_request_response CHECK (
        (response_status = 'OPEN' AND response_message IS NULL AND responded_at IS NULL)
        OR (response_status = 'RESPONDED' AND response_message IS NOT NULL AND responded_at IS NOT NULL)
    ),
    CONSTRAINT chk_information_request_message CHECK (length(btrim(request_message)) > 0),
    CONSTRAINT chk_information_response_message CHECK (response_message IS NULL OR length(btrim(response_message)) > 0)
);

CREATE INDEX idx_information_requests_incident_requested
    ON incident_information_requests(incident_id, requested_at ASC, information_request_id ASC);

COMMIT;
